// Numeric heat cell: faint metric-colored background scaled by value
function NumCell({ value, max, color }) {
  if (!value) return <span style={{ color: "#cdd3d9" }}>·</span>;
  const alpha = 0.1 + 0.32 * (value / max);
  return (
    <span
      style={{
        display: "inline-block",
        minWidth: 30,
        padding: "3px 8px",
        borderRadius: 5,
        background:
          color +
          Math.round(alpha * 255)
            .toString(16)
            .padStart(2, "0"),
        color: GRAPHITE,
        fontWeight: 700,
        fontSize: 13,
        textAlign: "center",
      }}
    >
      {value}
    </span>
  );
}

// Resolve a sort value for a server row given the active sort key
function getSortVal(row, key) {
  if (key === "server") return row.server;
  if (key === "dTickets") return row.dTickets ?? 0;
  if (key === "dUsers") return row.dUsers ?? 0;
  if (key.startsWith("t:")) return row.t[key.slice(2)] ?? 0;
  if (key.startsWith("u:")) return row.u[key.slice(2)] ?? 0;
  return row.ticketsTotal;
}

function DeltaBadge({ value }) {
  const increase = "#c0563a",
    decrease = "#26a987",
    flat = "#9aa3ab";
  if (value === 0) {
    return (
      <span style={{ color: flat, fontWeight: 600, fontSize: 13 }}>0</span>
    );
  }
  const positive = value > 0;
  const color = positive ? increase : decrease;
  const arrow = positive ? "▲" : "▼";
  return (
    <span
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: 4,
        color,
        fontWeight: 700,
        fontSize: 13,
      }}
    >
      <span style={{ fontSize: 9 }}>{arrow}</span>
      {positive ? `+${value}` : value}
    </span>
  );
}

